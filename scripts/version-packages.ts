import { readdirSync, readFileSync, writeFileSync } from "fs"
import { join } from "path"
import {
  MIN_CLIENT_VERSIONS,
  MIN_SERVER_VERSIONS,
} from "../packages/versions/src/generated"

const root = join(import.meta.dir, "..")
const changesetDir = join(root, ".changeset")

// A changeset marks a breaking release with a summary line starting "BREAKING:".
const breakingPackages = (): Set<string> => {
  const packages = new Set<string>()
  for (const file of readdirSync(changesetDir)) {
    if (!file.endsWith(".md") || file === "README.md") continue
    const content = readFileSync(join(changesetDir, file), "utf8")
    const [, frontmatter = "", body = ""] = content.split("---")
    if (!/^BREAKING:/m.test(body)) continue
    for (const match of frontmatter.matchAll(/^["']?([^"':\s]+)["']?:/gm)) {
      packages.add(match[1]!)
    }
  }
  return packages
}

const appVersion = (app: string): string =>
  JSON.parse(readFileSync(join(root, "apps", app, "package.json"), "utf8"))
    .version

const breaking = breakingPackages()

const version = Bun.spawnSync([process.execPath, "x", "changeset", "version"], {
  cwd: root,
  stdio: ["inherit", "inherit", "inherit"],
})
if (version.exitCode !== 0) process.exit(version.exitCode)

const latest = {
  server: appVersion("api"),
  desktop: appVersion("desktop"),
  mobile: appVersion("mobile"),
}

const minClient = { ...MIN_CLIENT_VERSIONS }
if (breaking.has("@refine/api")) {
  minClient.desktop = latest.desktop
  minClient.mobile = latest.mobile
}

const minServer = { ...MIN_SERVER_VERSIONS }
if (breaking.has("@refine/desktop")) minServer.desktop = latest.server
if (breaking.has("@refine/mobile")) minServer.mobile = latest.server

const file = `// Generated by scripts/version-packages.ts. Do not edit.
export const LATEST_VERSIONS = {
  server: "${latest.server}",
  desktop: "${latest.desktop}",
  mobile: "${latest.mobile}",
} as const

export const MIN_CLIENT_VERSIONS = {
  desktop: "${minClient.desktop}",
  mobile: "${minClient.mobile}",
} as const

export const MIN_SERVER_VERSIONS = {
  desktop: "${minServer.desktop}",
  mobile: "${minServer.mobile}",
} as const
`

writeFileSync(join(root, "packages/versions/src/generated.ts"), file)

console.log({ latest, minClient, minServer })
